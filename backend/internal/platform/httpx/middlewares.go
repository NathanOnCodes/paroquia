package httpx

import (
	"log/slog"
	"runtime/debug"
	"time"

	"github.com/gofiber/fiber/v3"
	"github.com/gofiber/fiber/v3/middleware/requestid"
)

// FiberErrorHandler is the application-wide error handler. It is plugged into
// fiber.Config.ErrorHandler so that every error — returned by a handler or
// produced by a recovered panic — is rendered with the same envelope.
func ManipuladorDeErros(logger *slog.Logger) fiber.ErrorHandler {
	return func(c fiber.Ctx, err error) error {
		status := fiber.StatusInternalServerError
		if e := DesembrulharErroAPI(err); e != nil {
			status = e.Status
		}

		logger.WarnContext(c.Context(), "request failed",
			slog.String("method", c.Method()),
			slog.String("path", c.Path()),
			slog.Int("status", status),
			slog.String("request_id", requestid.FromContext(c)),
			slog.String("error", err.Error()),
		)
		return EscreverErro(c, err)
	}
}

// UnwrapAPIError returns the *APIError carried by err, if any.
func DesembrulharErroAPI(err error) *ErroAPI {
	for e := err; e != nil; {
		if ae, ok := e.(*ErroAPI); ok {
			return ae
		}
		u, ok := e.(interface{ Unwrap() error })
		if !ok {
			return nil
		}
		e = u.Unwrap()
	}
	return nil
}

// Recover converts panics into a generic 500 and logs the stack trace. It
// never exposes the panic value to the client.
func RecuperarPanico(logger *slog.Logger) fiber.Handler {
	return func(c fiber.Ctx) error {
		defer func() {
			if r := recover(); r != nil {
				logger.ErrorContext(c.Context(), "panic recovered",
					slog.Any("panic", r),
					slog.String("path", c.Path()),
					slog.String("method", c.Method()),
					slog.String("stack", string(debug.Stack())),
				)
				_ = EscreverErro(c, ErroInterno("Erro inesperado", nil))
			}
		}()
		return c.Next()
	}
}

// RequestLogger records one structured line per request.
func RegistradorDeRequisicoes(logger *slog.Logger) fiber.Handler {
	return func(c fiber.Ctx) error {
		start := time.Now()
		err := c.Next()

		status := c.Response().StatusCode()
		if e := DesembrulharErroAPI(err); e != nil {
			status = e.Status
		}

		logger.InfoContext(c.Context(), "http request",
			slog.String("method", c.Method()),
			slog.String("path", c.Path()),
			slog.Int("status", status),
			slog.Duration("duration", time.Since(start)),
			slog.String("request_id", requestid.FromContext(c)),
		)
		return err
	}
}

// RequestID returns the request id generated by the requestid middleware.
func IDDaRequisicao(c fiber.Ctx) string { return requestid.FromContext(c) }
